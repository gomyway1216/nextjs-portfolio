/** The published odds of a hand around the cut-off, by its ranks; a hand not written out here is a mistake. */
export function publishedRanks(ranks: readonly Rank[]): ScoreOdds {
  const odds = PUBLISHED_RANKS[ranks.join('-')];
  if (!odds) throw new Error(`the odds of ${ranks.join('-')} are not written out in published.ts`);
  return odds;
}
