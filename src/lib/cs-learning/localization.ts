export function getCsLearningCopy(language: unknown) {
  return csLearningCopy[normalizeCsLearningLanguage(language)];
}

export function formatCsLearningCopy(
  template: string,
  values: Record<string, string | number>
) {
  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => String(values[key] ?? ''));
}
