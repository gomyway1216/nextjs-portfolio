export type CsLearningLanguage = 'en' | 'ja';

export function normalizeCsLearningLanguage(language: unknown): CsLearningLanguage {
  return typeof language === 'string' && language.toLowerCase().startsWith('ja') ? 'ja' : 'en';
}

